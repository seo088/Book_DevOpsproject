def get_keywords_map():
    """
    키워드 검색을 빠르게 하기 위해 {keyword: tag_name} 구조의 리스트를 반환합니다.
    """
    keyword_map = []
    for category, tags in TAG_DICT.items():
        for tag_name, keywords in tags.items():
            for keyword in keywords:
                keyword_map.append({
                    "keyword": keyword,
                    "tag_name": tag_name,
                    "category": category
                })
    return keyword_map